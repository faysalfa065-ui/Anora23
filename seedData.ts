export function createCinematicSvgDataUri(
  title: string,
  subtitle: string,
  c1: string,
  c2: string,
  accent: string = '#F5C518',
  aspect: 'poster' | 'backdrop' | 'person' = 'poster'
): string {
  const w = aspect === 'backdrop' ? 800 : 400;
  const h = aspect === 'backdrop' ? 450 : aspect === 'person' ? 400 : 600;
  const safeTitle = title.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const safeSub = subtitle.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}">
    <defs>
      <linearGradient id="bg" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${c1}" />
        <stop offset="55%" stop-color="${c2}" />
        <stop offset="100%" stop-color="#070709" />
      </linearGradient>
      <radialGradient id="glow" cx="70%" cy="28%" r="60%">
        <stop offset="0%" stop-color="${accent}" stop-opacity="0.32" />
        <stop offset="100%" stop-color="#000000" stop-opacity="0" />
      </radialGradient>
    </defs>
    <rect width="${w}" height="${h}" fill="url(#bg)" />
    <rect width="${w}" height="${h}" fill="url(#glow)" />
    <circle cx="${w * 0.72}" cy="${h * 0.3}" r="${Math.min(w, h) * 0.26}" fill="none" stroke="${accent}" stroke-opacity="0.22" stroke-width="2" />
    <circle cx="${w * 0.72}" cy="${h * 0.3}" r="${Math.min(w, h) * 0.16}" fill="${accent}" fill-opacity="0.08" />
    <path d="M 0 ${h * 0.65} Q ${w * 0.45} ${h * 0.52} ${w} ${h * 0.75} L ${w} ${h} L 0 ${h} Z" fill="#09090b" fill-opacity="0.72" />
    <rect x="${w * 0.08}" y="${h * 0.08}" width="54" height="22" rx="4" fill="${accent}" fill-opacity="0.9" />
    <text x="${w * 0.08 + 27}" y="${h * 0.08 + 15}" font-family="Inter, system-ui, sans-serif" font-size="11" font-weight="800" fill="#0A0A0B" text-anchor="middle">ANORA</text>
    <text x="${w * 0.08}" y="${h * 0.78}" font-family="Inter, system-ui, sans-serif" font-size="${aspect === 'backdrop' ? 34 : 26}" font-weight="900" fill="#FFFFFF" letter-spacing="-0.5">${safeTitle}</text>
    <text x="${w * 0.08}" y="${h * 0.85}" font-family="Inter, system-ui, sans-serif" font-size="${aspect === 'backdrop' ? 16 : 13}" font-weight="600" fill="${accent}" letter-spacing="1.5">${safeSub.toUpperCase()}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

